/** Re-localize already displayed results without changing controller state or
 * re-requesting anything. Internal error identifiers are preserved verbatim. */
export function indicesStatus(language: Language, status: string): string {
  const keys: EvaluationKey[] = [
    "connected",
    "authenticated",
    "healthy",
    "verifiedEffects",
    "uncertain",
    "busy",
    "notReady",
  ];
  for (const key of keys) {
    if (languages.some((source) => evalText(source, key) === status))
      return evalText(language, key);
  }
  const stages: Record<string, IndicesKey> = {
    buying: "buying",
    selling: "selling",
    active: "progress",
    claimable: "claiming",
    redeemed: "progress",
    uncertain: "recoveryNote",
    authorization_pending: "processing",
    SETTLEMENT_RELEASE_VERIFICATION_REQUIRED: "blocked",
  };
  if (stages[status]) return indicesText(language, stages[status]);
  if (status.startsWith("EVAL_"))
    return `${evalText(language, "error")}\n${status}`;
  return status;
}
